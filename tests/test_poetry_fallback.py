def _write_existing_bom(path, components):
    path.write_text(json.dumps({
        'bomFormat': 'CycloneDX',
        'specVersion': '1.5',
        'serialNumber': 'urn:uuid:00000000-0000-0000-0000-000000000000',
        'version': 1,
        'components': components,
    }))


def test_merge_adds_new_components(tmp_path):
    bom = tmp_path / 'bom.json'
    _write_existing_bom(bom, [
        {'type': 'library', 'bom-ref': 'pkg:pypi/foo@1.0',
         'name': 'foo', 'version': '1.0'},
    ])
    new = [
        {'type': 'library', 'bom-ref': 'pkg:pypi/bar@2.0',
         'name': 'bar', 'version': '2.0'},
    ]
    added, total = poetry_fallback.merge_components_into_bom(str(bom), new)
    assert added == 1 and total == 2
    merged = json.loads(bom.read_text())
    refs = {c['bom-ref'] for c in merged['components']}
    assert refs == {'pkg:pypi/foo@1.0', 'pkg:pypi/bar@2.0'}


def test_merge_dedupes_against_existing_purl(tmp_path):
    bom = tmp_path / 'bom.json'
    _write_existing_bom(bom, [
        {'type': 'library', 'bom-ref': 'pkg:pypi/foo@1.0',
         'purl': 'pkg:pypi/foo@1.0', 'name': 'foo', 'version': '1.0'},
    ])
    new = [
        {'type': 'library', 'bom-ref': 'pkg:pypi/foo@1.0',
         'name': 'foo', 'version': '1.0'},
    ]
    added, total = poetry_fallback.merge_components_into_bom(str(bom), new)
    assert added == 0 and total == 1


def test_merge_refreshes_serial_when_added(tmp_path):
    """DT keys re-uploads off serialNumber. If we add components but don't
    bump the serial, DT may treat the BOM as a no-op and skip processing."""
    bom = tmp_path / 'bom.json'
    _write_existing_bom(bom, [])
    original_serial = json.loads(bom.read_text())['serialNumber']
    poetry_fallback.merge_components_into_bom(str(bom), [
        {'type': 'library', 'bom-ref': 'pkg:pypi/foo@1.0',
         'name': 'foo', 'version': '1.0'},
    ])
    new_serial = json.loads(bom.read_text())['serialNumber']
    assert new_serial != original_serial


def test_merge_rejects_non_cyclonedx_doc(tmp_path):
    bom = tmp_path / 'bom.json'
    bom.write_text(json.dumps({'spdxVersion': 'SPDX-2.3', 'something': 'else'}))
    with pytest.raises(poetry_fallback.PoetryFallbackError):
        poetry_fallback.merge_components_into_bom(str(bom), [])


def test_merge_handles_missing_components_array(tmp_path):
    bom = tmp_path / 'bom.json'
    bom.write_text(json.dumps({
        'bomFormat': 'CycloneDX',
        'specVersion': '1.5',
        'serialNumber': 'urn:uuid:0',
    }))
    added, total = poetry_fallback.merge_components_into_bom(str(bom), [
        {'type': 'library', 'bom-ref': 'pkg:pypi/foo@1.0',
         'name': 'foo', 'version': '1.0'},
    ])
    assert added == 1 and total == 1
