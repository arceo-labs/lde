def test_synthesize_bom_minimum_cyclonedx_shape(tmp_path):
    lock = tmp_path / 'poetry.lock'
    lock.write_text(_VALID_LOCK)
    bom = poetry_fallback.synthesize_bom(str(lock), 'example-org/probabilism', '1.2.3')
    assert bom['bomFormat'] == 'CycloneDX'
    assert bom['specVersion'] == '1.5'
    assert bom['serialNumber'].startswith('urn:uuid:')
    assert bom['metadata']['component']['name'] == 'example-org/probabilism'
    assert bom['metadata']['component']['version'] == '1.2.3'
    assert len(bom['components']) == 2


