def test_parses_valid_lockfile_components(tmp_path):
    lock = tmp_path / 'poetry.lock'
    lock.write_text(_VALID_LOCK)
    components = poetry_fallback.parse_poetry_lock(str(lock))
    assert len(components) == 2
    by_name = {c['name']: c for c in components}
    assert 'annotated-types' in by_name
    assert by_name['annotated-types']['purl'] == 'pkg:pypi/annotated-types@0.7.0'
    assert by_name['annotated-types']['hashes'] == [
        {'alg': 'SHA-256',
         'content': '1f02e8b43a8fbbc3f3e0d4f0f4bfc8131bcb4eebe8849b8e5c773f3a1c582a53'},
    ]


def test_purl_normalises_name_per_pep503(tmp_path):
    """Underscores and dots in a Poetry name must collapse to '-' so the
    purl matches what DT will compute from any other resolver. Otherwise
    the same package shows up twice in DT under different bom-refs."""
    lock = tmp_path / 'poetry.lock'
    lock.write_text('''[[package]]
name = "Foo_Bar.Baz"
version = "1.0"
description = "x"
optional = false
python-versions = ">=3"
groups = ["main"]
files = []
''')
    comps = poetry_fallback.parse_poetry_lock(str(lock))
    assert comps[0]['name'] == 'foo-bar-baz'
    assert comps[0]['purl'] == 'pkg:pypi/foo-bar-baz@1.0'


def test_pep440_local_version_segment_passes(tmp_path):
    """torch wheels often use a '+cu121' local version segment. PEP 440
    permits it, so our validator must accept it."""
    lock = tmp_path / 'poetry.lock'
    lock.write_text(_VALID_LOCK)
    comps = poetry_fallback.parse_poetry_lock(str(lock))
    by_name = {c['name']: c for c in comps}
    assert by_name['torch']['version'] == '2.4.0+cu121'
    assert '%2B' in by_name['torch']['purl']  # '+' is URL-encoded in purl


def test_invalid_name_dropped_silently(tmp_path):
    """A malicious or corrupt lock with shell metacharacters in the name
    must not make it into the BOM. Drop the row, keep the others."""
    lock = tmp_path / 'poetry.lock'
    lock.write_text('''[[package]]
name = "../../etc/passwd"
version = "1.0"
description = "evil"
optional = false
python-versions = ">=3"
groups = ["main"]
files = []

[[package]]
name = "ok-pkg"
version = "1.0"
description = "fine"
optional = false
python-versions = ">=3"
groups = ["main"]
files = []
''')
    comps = poetry_fallback.parse_poetry_lock(str(lock))
    assert [c['name'] for c in comps] == ['ok-pkg']


def test_non_sha256_hash_dropped(tmp_path):
    """An md5-only entry must not surface as if it were sha256. The
    component is kept (purl + name + version) but no hashes array."""
    lock = tmp_path / 'poetry.lock'
    lock.write_text('''[[package]]
name = "x"
version = "1"
description = "x"
optional = false
python-versions = ">=3"
groups = ["main"]
files = [
    {file = "x.whl", hash = "md5:0123456789abcdef0123456789abcdef"},
]
''')
    comps = poetry_fallback.parse_poetry_lock(str(lock))
    assert 'hashes' not in comps[0]


def test_dedupes_repeated_packages(tmp_path):
    lock = tmp_path / 'poetry.lock'
    lock.write_text(_DEDUPED_LOCK)
    comps = poetry_fallback.parse_poetry_lock(str(lock))
    purls = [c['purl'] for c in comps]
    assert len(purls) == len(set(purls)) == 2


def test_malformed_toml_raises(tmp_path):
    lock = tmp_path / 'poetry.lock'
    lock.write_text('not actually toml [[[')
    with pytest.raises(poetry_fallback.PoetryFallbackError):
        poetry_fallback.parse_poetry_lock(str(lock))


def test_missing_file_raises(tmp_path):
    with pytest.raises(poetry_fallback.PoetryFallbackError):
        poetry_fallback.parse_poetry_lock(str(tmp_path / 'no-such-file.lock'))


